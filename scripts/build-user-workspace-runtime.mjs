import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = resolve(root, 'app/generated/user-workspace-runtime.generated.ts');
const pathBrowserifyEntry = createRequire(resolve(root, 'cloudchef-agent/package.json')).resolve('path-browserify');

/**
 * Vite resolves `?raw` imports natively; esbuild does not. The bundled builder skills are
 * markdown kept as markdown in this repository, so both bundlers have to read them the same way.
 */
const rawTextPlugin = {
  name: 'cloudchef-raw-text',
  setup(pluginBuild) {
    pluginBuild.onResolve({ filter: /\?raw$/ }, (args) => {
      const specifier = args.path.slice(0, -'?raw'.length);
      // Plugin resolution runs before esbuild's tsconfig handling, so the app's `~/` alias
      // has to be applied here for raw imports.
      return {
        path: specifier.startsWith('~/')
          ? resolve(root, 'app', specifier.slice('~/'.length))
          : resolve(args.resolveDir, specifier),
        namespace: 'cloudchef-raw-text',
      };
    });
    pluginBuild.onLoad({ filter: /.*/, namespace: 'cloudchef-raw-text' }, async (args) => ({
      contents: await readFile(args.path, 'utf8'),
      loader: 'text',
    }));
  },
};

/**
 * builder-skills.ts is bundled twice: by Vite into the control-plane Worker and by this
 * script into the user workspace runtime (BuilderAgent runs there). Only Vite implements
 * import.meta.glob, so the react-start skill tree is inlined into a generated module both
 * bundlers import as plain TypeScript. The content stays byte-identical to the version the
 * seeded frozen lockfile installs because it is read from template/node_modules here.
 */
const reactStartSkillRoot = resolve(root, 'template/node_modules/@tanstack/react-start/skills/react-start');
const skillAssetsOutputPath = resolve(root, 'app/generated/builder-skill-assets.generated.ts');

async function readSkillTree(directory, prefix = '') {
  const files = {};
  for (const entry of (await readdir(directory, { withFileTypes: true })).sort((a, b) =>
    a.name.localeCompare(b.name),
  )) {
    const relativePath = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) {
      Object.assign(files, await readSkillTree(resolve(directory, entry.name), relativePath));
    } else if (entry.isFile()) {
      files[relativePath] = await readFile(resolve(directory, entry.name), 'utf8');
    }
  }
  return files;
}

const reactStartSkillFiles = await readSkillTree(reactStartSkillRoot);
if (!reactStartSkillFiles['SKILL.md']) {
  throw new Error(`The react-start skill at ${reactStartSkillRoot} is missing SKILL.md; run pnpm install first.`);
}
await mkdir(dirname(skillAssetsOutputPath), { recursive: true });
await writeFile(
  skillAssetsOutputPath,
  `// Generated by scripts/build-user-workspace-runtime.mjs. Do not edit.\n` +
    `export const REACT_START_SKILL_FILES: Readonly<Record<string, string>> = ${JSON.stringify(reactStartSkillFiles)};\n`,
);

const result = await build({
  entryPoints: [resolve(root, 'user-workspace-runtime/src/index.ts')],
  bundle: true,
  write: false,
  format: 'esm',
  platform: 'neutral',
  conditions: ['workerd', 'worker', 'browser'],
  mainFields: ['browser', 'module', 'main'],
  alias: { path: pathBrowserifyEntry },
  target: 'es2022',
  minify: true,
  legalComments: 'none',
  define: { 'import.meta.url': JSON.stringify('file:///bundle/workspace-runtime.mjs') },
  banner: {
    js: 'import { createRequire as __cloudchefCreateRequire } from "node:module"; const require = __cloudchefCreateRequire("file:///bundle/workspace-runtime.mjs");',
  },
  external: ['cloudflare:*', 'node:*'],
  plugins: [rawTextPlugin],
});
const source = result.outputFiles[0]?.text;
if (!source) {
  throw new Error('The user-owned workspace runtime bundle was not generated.');
}
// esbuild leaves import.meta expressions it does not implement in place. A bare
// import.meta.url misses the define above, and Vite-only functions like import.meta.glob
// throw when the Worker module is first evaluated - which surfaces as a failed workspace
// provisioning, not a build error. Reject the bundle here instead. (Benign property reads
// such as Vite's import.meta.hot?. guards evaluate to undefined and are allowed.)
for (const forbidden of ['import.meta.url', 'import.meta.glob(', 'import.meta.env']) {
  if (source.includes(forbidden)) {
    throw new Error(`The user-owned workspace runtime bundle contains an unsupported ${forbidden} reference.`);
  }
}
const sha256 = createHash('sha256').update(source).digest('hex');
const migrationDirectory = resolve(root, 'user-workspace-migrations');
const migrationNames = (await readdir(migrationDirectory)).filter((name) => /^\d{4}_.+\.sql$/.test(name)).sort();
const migrations = await Promise.all(
  migrationNames.map(async (name) => ({ name, sql: await readFile(resolve(migrationDirectory, name), 'utf8') })),
);
const generated =
  `// Generated by scripts/build-user-workspace-runtime.mjs. Do not edit.\n` +
  `export const USER_WORKSPACE_RUNTIME_SOURCE = ${JSON.stringify(source)};\n` +
  `export const USER_WORKSPACE_RUNTIME_SHA256 = ${JSON.stringify(sha256)};\n` +
  `export const USER_WORKSPACE_DATA_MIGRATIONS = ${JSON.stringify(migrations)} as const;\n`;
await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, generated);
