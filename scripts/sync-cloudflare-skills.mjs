import { writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Vendors Cloudflare's official agent skills (github.com/cloudflare/skills, Apache-2.0) into the builder,
 * pinned to one commit, so the agent reads Cloudflare's own current guidance instead of a hand-written
 * copy that drifts. Run `node scripts/sync-cloudflare-skills.mjs [commit]` to update (default: main).
 */
const REPOSITORY = 'cloudflare/skills';
const CLOUDFLARE_SKILL_NAMES = ['cf-cli', 'workers-best-practices', 'durable-objects', 'agents-sdk'];
const OUTPUT = resolve(
  dirname(fileURLToPath(import.meta.url)),
  '../app/lib/.server/llm/skills/cloudflare-skills.vendored.ts',
);

async function github(path) {
  const response = await fetch(`https://api.github.com/repos/${REPOSITORY}/${path}`, {
    headers: { Accept: 'application/vnd.github+json', 'User-Agent': 'cloudchef-skill-sync' },
  });
  if (!response.ok) {
    throw new Error(`GitHub refused ${path} (${response.status}).`);
  }
  return response.json();
}

async function raw(commit, path) {
  const response = await fetch(`https://raw.githubusercontent.com/${REPOSITORY}/${commit}/${path}`);
  if (!response.ok) {
    throw new Error(`Could not fetch ${path} at ${commit} (${response.status}).`);
  }
  return response.text();
}

const requested = process.argv[2] ?? 'main';
const { sha: commit } = await github(`commits/${requested}`);
const { tree } = await github(`git/trees/${commit}?recursive=1`);
const license = await raw(commit, 'LICENSE');
const skills = [];
for (const name of CLOUDFLARE_SKILL_NAMES) {
  const prefix = `skills/${name}/`;
  const paths = tree
    .filter((entry) => entry.type === 'blob' && entry.path.startsWith(prefix))
    .map((entry) => entry.path)
    .sort();
  if (!paths.includes(`${prefix}SKILL.md`)) {
    throw new Error(`${REPOSITORY}@${commit} has no ${prefix}SKILL.md.`);
  }
  const files = [];
  for (const path of paths) {
    files.push([path.slice(prefix.length), await raw(commit, path)]);
  }
  files.push(['LICENSE', license]);
  skills.push({ name, files });
}
await writeFile(
  OUTPUT,
  `// Generated by scripts/sync-cloudflare-skills.mjs from github.com/${REPOSITORY}@${commit}.\n` +
    `// Cloudflare's skills are licensed under the Apache License 2.0 (each skill's LICENSE file). Do not edit.\n` +
    `export const CLOUDFLARE_SKILLS: readonly { name: string; files: readonly (readonly [string, string])[] }[] = ${JSON.stringify(skills)};\n`,
);
console.log(`Vendored ${skills.length} Cloudflare skills from ${REPOSITORY}@${commit}.`);
