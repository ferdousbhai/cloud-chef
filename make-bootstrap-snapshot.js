import { promises as fs } from 'node:fs';
import path from 'node:path';
import { execFile as execFileCallback } from 'node:child_process';
import { promisify } from 'node:util';
import { gzipSync } from 'node:zlib';
import { listTemplateSourceFiles, templateSourceDigest } from './scripts/template-source.mjs';

const execFile = promisify(execFileCallback);

const WORKERS_AI_MODEL_MODULE = 'app/lib/workers-ai-model.ts';
const TEMPLATE_MODEL_MODULE = 'template/src/workers-ai.shared.ts';
// The same read `scripts/ops-report.mjs` performs, for the same reason: the pin is hand-authored
// TypeScript that imports zod, and neither a plain node script nor this one can import it.
const PINNED_BUILDER_MODEL_PATTERN = /CLOUDFLARE_WORKERS_AI_MODEL = '(@cf\/[^']+)'/;

async function main() {
  const inputDir = 'template';
  const absoluteInputDir = path.resolve(inputDir);
  // Before the file listing, so the snapshot embeds the pin this run just emitted rather than
  // whatever the previous one left behind.
  await writeTemplateModelModule();
  console.log('Listing tracked and untracked unignored template files...');
  const files = listTemplateSourceFiles(process.cwd());
  console.log('Verifying the standalone pnpm lockfile...');
  await execFile('pnpm', ['install', '--lockfile-only', '--frozen-lockfile'], { cwd: absoluteInputDir });
  await writeBuilderTemplateModule(files, absoluteInputDir);
  console.log('Done!');
}

/**
 * The generated application's own copy of the builder's model pin, emitted rather than maintained.
 *
 * The two copies are not the same risk. Re-pinning the control-plane constant moves every
 * CloudChef build at the next deploy; the template's literal is baked into each generated app and
 * deployed into the user's own Cloudflare account, where there is no catalog discovery and no
 * failover, and apps already out there stay frozen on whatever it said. So re-pinning the builder
 * and forgetting the template ships new apps on a model CloudChef itself has already left. A test
 * used to compare the two as text, which caught the drift after it was written; generating the
 * copy means there is no second value to drift.
 */
async function writeTemplateModelModule() {
  const source = await fs.readFile(WORKERS_AI_MODEL_MODULE, 'utf8');
  const pinned = PINNED_BUILDER_MODEL_PATTERN.exec(source)?.[1];
  if (!pinned) {
    throw new Error(`No CLOUDFLARE_WORKERS_AI_MODEL pin could be read from ${WORKERS_AI_MODEL_MODULE}.`);
  }
  // Double quotes and a trailing newline because `template/**` is Prettier-checked under its own
  // override (`singleQuote: false`), and a generated file has to be born already formatted.
  const output = [
    '// Generated by make-bootstrap-snapshot.js. Do not edit by hand.',
    `// Mirrors CLOUDFLARE_WORKERS_AI_MODEL in ${WORKERS_AI_MODEL_MODULE}.`,
    `export const WORKERS_AI_CODING_MODEL = "${pinned}";`,
    '',
  ].join('\n');
  await fs.writeFile(TEMPLATE_MODEL_MODULE, output);
  console.log(`Wrote the generated application's model pin (${pinned}).`);
}

async function writeBuilderTemplateModule(files, templateDir) {
  const sourceSha256 = templateSourceDigest(process.cwd(), files);
  const entries = await Promise.all(files.map((file) => builderTemplateEntry(file, templateDir)));
  const compressed = gzipSync(Buffer.from(JSON.stringify(entries)), { level: 9 });
  const output = [
    '// Generated by make-bootstrap-snapshot.js. Do not edit by hand.',
    `export const BUILDER_TEMPLATE_SOURCE_SHA256 = '${sourceSha256}';`,
    '// prettier-ignore',
    `export const BUILDER_TEMPLATE_GZIP_BASE64 = '${compressed.toString('base64')}';`,
    '',
  ].join('\n');
  await fs.writeFile('app/agents/builder-template.generated.ts', output);
  console.log(`Wrote server Builder template (${compressed.byteLength} gzip bytes).`);
}

async function builderTemplateEntry(file, templateDir) {
  const bytes = await fs.readFile(file);
  const text = decodeUtf8Text(bytes);
  return {
    path: `/home/project/${path.relative(templateDir, file).replaceAll(path.sep, '/')}`,
    content: text ?? bytes.toString('base64'),
    encoding: text === null ? 'base64' : 'utf8',
  };
}

function decodeUtf8Text(bytes) {
  if (bytes.some((byte) => byte < 0x20 && byte !== 0x09 && byte !== 0x0a && byte !== 0x0d)) {
    return null;
  }
  const text = bytes.toString('utf8');
  return Buffer.from(text, 'utf8').equals(bytes) ? text : null;
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
});
